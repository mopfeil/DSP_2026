/*
 * Sheet 10 -- Exercise 10.2: filter design tool (student template)
 *
 * Build and run:   gcc -O2 -o filterdesign filterdesign.c -lm
 *                  ./filterdesign            (writes knock_filter.h)
 * (filtdesign.h, asciiplot.h in the same directory)
 *
 * Designs the knock band-pass of Exercise 10.1
 *   fs = 25 kHz, pass band 6.0..7.0 kHz (max. 1 dB loss),
 *   stop bands <= 5.0 kHz and >= 8.0 kHz (min. 40 dB attenuation)
 * as a linear-phase FIR filter (window method) and as an IIR Butterworth
 * band-pass (bilinear transform, biquad cascade), checks the specification,
 * and exports the coefficients as C header (float, Q15 / Q14) for the
 * Wokwi sketches of Sheets 10 and 12.
 */
#include <stdio.h>
#include <stdint.h>
#include <math.h>
#include "filtdesign.h"
#include "asciiplot.h"

#define FS    25000.0
#define FP1    6000.0     /* pass band          */
#define FP2    7000.0
#define FST1   5000.0     /* stop-band edges    */
#define FST2   8000.0
#define AP        1.0     /* dB                 */
#define AS       40.0     /* dB                 */
#define FIR_N    83       /* chosen FIR length (Hamming, see 10.1) */
#define F0     6500.0     /* centre (knock mode 1) */
#define BW2     400.0     /* bandwidth of the single biquad (matched to tau) */
#define NF      500       /* frequency grid for plots */

/* worst-case pass-band loss and stop-band gain (dB) of a response given
   by a callback-free approach: we evaluate FIR or SOS explicitly */
static void check_fir(const double *h, int N, double *pass_min, double *pass_max,
                      double *stop_max)
{
    int i;
    *pass_min = 1e9; *pass_max = -1e9; *stop_max = -1e9;
    for (i = 0; i <= 500; i++) {
        double f = 0.5 * FS * i / 500.0, m = fd_db(c_abs(fd_fir_resp(h, N, f, FS)));
        if (f >= FP1 && f <= FP2) { if (m < *pass_min) *pass_min = m; if (m > *pass_max) *pass_max = m; }
        if (f <= FST1 || f >= FST2) { if (m > *stop_max) *stop_max = m; }
    }
}

static void check_sos(const biquad_t *s, int ns, double *pass_min, double *pass_max,
                      double *stop_max)
{
    int i;
    *pass_min = 1e9; *pass_max = -1e9; *stop_max = -1e9;
    for (i = 0; i <= 500; i++) {
        double f = 0.5 * FS * i / 500.0, m = fd_db(c_abs(fd_sos_resp(s, ns, f, FS)));
        if (f >= FP1 && f <= FP2) { if (m < *pass_min) *pass_min = m; if (m > *pass_max) *pass_max = m; }
        if (f <= FST1 || f >= FST2) { if (m > *stop_max) *stop_max = m; }
    }
}

